#!/usr/bin/env python3
"""Migrate existing postprocessing results to consolidated format.

This script takes the 44 files per configuration generated by the old
postprocessing pipeline and reorganizes them into the new 4-file structure.

NO COMPUTATION - Just file reorganization!

Usage:
    python migrate_postprocessing_results.py \\
        --input results/results_bluesky \\
        --output results_consolidated \\
        --dataset bluesky
"""

import argparse
import json
import sys
from pathlib import Path
from typing import Dict, List
import pandas as pd


def find_configs(input_dir: Path) -> List[Dict]:
    """Find all configurations with postprocessing results.

    Returns:
        List of dicts with {config_name, model_dir, base_path}
    """
    configs = []

    # Look for *_optimal_response.json files as markers
    for json_file in input_dir.rglob('*_optimal_response.json'):
        config_name = json_file.stem.replace('_optimal_response', '')
        model_dir = json_file.parent.name

        # Skip if this looks like a simulation output dir structure
        # (we want the postprocessing results)
        base_path = json_file.parent

        configs.append({
            'config_name': config_name,
            'model_dir': model_dir,
            'base_path': base_path
        })

    return configs


def migrate_configuration(config: Dict, output_base: Path, dataset: str):
    """Migrate one configuration's 44 files to 4 consolidated files.

    Args:
        config: Config dict with config_name, model_dir, base_path
        output_base: Base output directory
        dataset: Dataset name
    """
    config_name = config['config_name']
    model_dir = config['model_dir']
    base_path = config['base_path']

    print(f"\n  Processing: {config_name}")

    # Create output directory
    output_dir = output_base / dataset / model_dir / config_name
    output_dir.mkdir(parents=True, exist_ok=True)

    # 1. RESPONSES.JSON - Consolidate optimal and random response files
    print("    [1/4] Migrating responses...")
    responses_data = {
        'config_name': config_name,
        'model': model_dir,
        'metadata': {},
        'responses': []
    }

    # Load optimal_response.json if exists
    optimal_file = base_path / f"{config_name}__optimal_response.json"
    if optimal_file.exists():
        with open(optimal_file) as f:
            data = json.load(f)
            # Extract metadata from first entry
            if data:
                for key in ['model', 'fine_tuned', 'retrieve_context', 'OPPU', 'n_style_examples']:
                    if key in data[0]:
                        responses_data['metadata'][key] = data[0][key]
                responses_data['model'] = data[0].get('model', model_dir)

            # Convert to consolidated format
            for entry in data:
                resp = {
                    'user': entry.get('user', ''),
                    'prompt_id': f"{entry.get('user', '')}___{entry.get('reply_to', '')}",
                    'candidates': entry.get('all_valid_responses', []),
                    'selected_indices': {},
                    'scores': {},
                    'metadata': {
                        'original_message': entry.get('original_message', ''),
                        'reply_to': entry.get('reply_to', '')
                    }
                }

                # Add selection methods
                if 'response' in entry or 'previous_response' in entry:
                    random_resp = entry.get('response', entry.get('previous_response'))
                    if random_resp and resp['candidates']:
                        try:
                            resp['selected_indices']['random'] = resp['candidates'].index(random_resp)
                        except ValueError:
                            pass

                if 'ML_best_response' in entry:
                    try:
                        resp['selected_indices']['ml'] = resp['candidates'].index(entry['ML_best_response'])
                        if 'ml_probabilities' in entry:
                            resp['scores']['ml'] = entry['ml_probabilities']
                    except ValueError:
                        pass

                if 'cosine_best_response' in entry:
                    try:
                        resp['selected_indices']['cosine'] = resp['candidates'].index(entry['cosine_best_response'])
                        if 'cosine_similarities' in entry:
                            resp['scores']['cosine'] = entry['cosine_similarities']
                    except ValueError:
                        pass

                responses_data['responses'].append(resp)

    # Save responses.json
    with open(output_dir / 'responses.json', 'w') as f:
        json.dump(responses_data, f, indent=2, ensure_ascii=False)
    print(f"      ✅ responses.json ({len(responses_data['responses'])} responses)")

    # 2. VALIDATION_RESULTS.JSON - Consolidate BERT results
    print("    [2/4] Migrating validation results...")
    validation_data = {
        'config_name': config_name,
        'model': responses_data['model'],
        'metadata': responses_data['metadata'],
        'results': {}
    }

    for method in ['random', 'ml', 'cosine']:
        bert_report_file = base_path / f"{config_name}__{method}_validation_data_bert_report.json"
        cm_file = base_path / f"{config_name}__{method}_validation_data_confusion_matrix.csv"
        trainer_file = base_path / f"{config_name}__{method}_validation_data_trainer_results.json"

        if bert_report_file.exists():
            with open(bert_report_file) as f:
                bert_metrics = json.load(f)

            confusion_matrix = [[0, 0], [0, 0]]
            if cm_file.exists():
                cm_df = pd.read_csv(cm_file, header=None)
                confusion_matrix = cm_df.values.tolist()

            validation_data['results'][method] = {
                'selection_method': method,
                'bert_metrics': bert_metrics,
                'confusion_matrix': confusion_matrix
            }

            # Add trainer results if available
            if trainer_file.exists():
                with open(trainer_file) as f:
                    validation_data['results'][method]['trainer_results'] = json.load(f)

    # Save validation_results.json
    with open(output_dir / 'validation_results.json', 'w') as f:
        json.dump(validation_data, f, indent=2, ensure_ascii=False)
    print(f"      ✅ validation_results.json ({len(validation_data['results'])} methods)")

    # 3. FEATURES.PARQUET - Consolidate feature files
    print("    [3/4] Migrating features...")
    features_dfs = []

    for method in ['random', 'ml', 'cosine']:
        features_file = base_path / f"{config_name}__{method}_validation_data_features.csv"
        labelled_file = base_path / f"{config_name}__{method}_validation_data_labelled.csv"

        # Try features_with_text_and_label first
        features_text_file = base_path / f"{config_name}__{method}_validation_data_features_with_text_and_label.csv"

        if features_text_file.exists():
            df = pd.read_csv(features_text_file)
            df['selection_method'] = method
            features_dfs.append(df)
        elif features_file.exists():
            df = pd.read_csv(features_file)
            df['selection_method'] = method
            features_dfs.append(df)
        elif labelled_file.exists():
            df = pd.read_csv(labelled_file)
            df['selection_method'] = method
            features_dfs.append(df)

    if features_dfs:
        combined_features = pd.concat(features_dfs, ignore_index=True)
        combined_features.to_parquet(output_dir / 'features.parquet', engine='pyarrow', compression='snappy')
        print(f"      ✅ features.parquet ({len(combined_features)} rows, {len(features_dfs)} methods)")
    else:
        print(f"      ⚠️  No feature files found")

    # 4. STATISTICS.JSON - Consolidate stats files
    print("    [4/4] Migrating statistics...")
    statistics_data = {
        'config_name': config_name,
        'model': responses_data['model'],
        'metadata': responses_data['metadata'],
        'statistics': {}
    }

    for method in ['random', 'ml', 'cosine']:
        stats = {}

        # Correlation stats
        corr_file = base_path / f"{config_name}__{method}_validation_data_labelled_from_labels_feature_correlation_stats.csv"
        if corr_file.exists():
            stats['correlation_stats'] = pd.read_csv(corr_file).to_dict('records')

        # Importance stats
        imp_file = base_path / f"{config_name}__{method}_validation_data_labelled_from_labels_feature_importance_stats.csv"
        if imp_file.exists():
            stats['importance_stats'] = pd.read_csv(imp_file).to_dict('records')

        # Empath significant features
        empath_file = base_path / f"{config_name}__{method}_validation_data_empath_significant_features.csv"
        if empath_file.exists():
            stats['empath_significant'] = pd.read_csv(empath_file).to_dict('records')

        # Median run agreement
        agreement_file = base_path / f"{config_name}__{method}_validation_data_from_labels_median_run_agreement.csv"
        if agreement_file.exists():
            stats['agreement_stats'] = pd.read_csv(agreement_file).to_dict('records')

        if stats:
            statistics_data['statistics'][method] = {
                'selection_method': method,
                **stats
            }

    # Save statistics.json
    with open(output_dir / 'statistics.json', 'w') as f:
        json.dump(statistics_data, f, indent=2, ensure_ascii=False)
    print(f"      ✅ statistics.json ({len(statistics_data['statistics'])} methods)")

    print(f"    ✅ Configuration migrated: {config_name}")


def main():
    """Main migration script."""
    parser = argparse.ArgumentParser(
        description="Migrate existing postprocessing results to consolidated format"
    )
    parser.add_argument(
        '--input',
        type=str,
        required=True,
        help='Input directory with existing results (e.g., results/results_bluesky)'
    )
    parser.add_argument(
        '--output',
        type=str,
        default='results_consolidated_postprocessing',
        help='Output directory for consolidated results'
    )
    parser.add_argument(
        '--dataset',
        type=str,
        required=True,
        choices=['bluesky', 'twitter', 'reddit'],
        help='Dataset name'
    )

    args = parser.parse_args()

    print("="*60)
    print("POSTPROCESSING RESULTS MIGRATION")
    print("="*60)
    print(f"Input:  {args.input}")
    print(f"Output: {args.output}")
    print(f"Dataset: {args.dataset}")
    print()

    # Setup paths
    input_dir = Path(args.input)
    if not input_dir.exists():
        print(f"❌ Error: Input directory not found: {input_dir}")
        sys.exit(1)

    output_dir = Path(args.output)
    output_dir.mkdir(parents=True, exist_ok=True)

    # Find all configurations
    print("🔍 Finding configurations...")
    configs = find_configs(input_dir)

    if not configs:
        print(f"❌ No configurations found in {input_dir}")
        sys.exit(1)

    print(f"✅ Found {len(configs)} configuration(s)")

    # Migrate each configuration
    print(f"\n{'='*60}")
    print(f"MIGRATING CONFIGURATIONS")
    print(f"{'='*60}")

    success_count = 0
    for i, config in enumerate(configs, 1):
        print(f"\n[{i}/{len(configs)}] {config['model_dir']}")
        try:
            migrate_configuration(config, output_dir, args.dataset)
            success_count += 1
        except Exception as e:
            print(f"    ❌ Error: {e}")
            import traceback
            traceback.print_exc()
            continue

    # Summary
    print(f"\n{'='*60}")
    print("✅ MIGRATION COMPLETE")
    print(f"{'='*60}")
    print(f"Configurations migrated: {success_count}/{len(configs)}")
    print(f"\nOld structure: ~{len(configs) * 44} files")
    print(f"New structure: ~{success_count * 4} files")
    print(f"Reduction: {(1 - (success_count * 4) / (len(configs) * 44)) * 100:.0f}%")
    print(f"\nOutput location:")
    print(f"  {output_dir}/{args.dataset}/")


if __name__ == "__main__":
    main()
